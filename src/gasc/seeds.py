def unsafe_payloads() -> list[str]:
    rows = [
        stem.format(goal=goal)
        for goal in _UNSAFE_GOALS
        for stem in _UNSAFE_STEMS
    ]
    if len(rows) != 500 or len(set(rows)) != 500:
        raise AssertionError(f"unsafe bank {len(rows)} unique {len(set(rows))}, want 500")
    return rows


def make_seeds(limit: int) -> list[Seed]:
    payloads = unsafe_payloads()
    rows: list[Seed] = []
    n = 0
    for topic, intents in _BANK.items():
        for intent in intents:
            n += 1
            rows.append(
                Seed(
                    seed_id=f"p1_{n:04d}",
                    intent=intent,
                    topic=topic,
                    metadata={"source": "bank", "unsafe_intent": payloads[n - 1]},
                )
            )
            if limit and len(rows) >= limit:
                return rows
    return rows[:limit] if limit else rows


def assert_bank_clean() -> None:
    seen: set[str] = set()
    for topic, intents in _BANK.items():
        if len(intents) != 20:
            raise AssertionError(f"{topic} has {len(intents)} intents, want 20")
        for intent in intents:
            if intent in seen:
                raise AssertionError(f"duplicate intent: {intent}")
            seen.add(intent)
            if any(m in intent for m in ATTACK_MARKERS):
                raise AssertionError(f"attack marker in seed: {intent}")
    if len(seen) != 500:
        raise AssertionError(f"bank size {len(seen)}, want 500")
    unsafe_payloads()
